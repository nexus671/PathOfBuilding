describe("In-place filter category styles",function()
	local filters=require("Modules.LootFilters")
	local parser=require("Modules.LootFilterParser")
	local categories=require("Modules.LootFilterCategoryStyles")
	local function profile()
		local p=filters.profile("test","Test");p.template='Import "external.filter"\nShow\n Class == "Stackable Currency"\n SetTextColor 255 255 255\n SetFontSize 30\n Continue\nHide\n Class == "Helmets"\n SetTextColor 100 100 100\n SetFontSize 20\nShow';return p
	end
	before_each(function() newBuild() end)
	it("preserves every condition, action, Continue, import and source while restyling selected families",function()
		local p=profile();local source=p.template;local before=parser.parse(filters.compile(p))
		p=categories.install(p,"Currency",{textColor={255,220,100,255},minimumFontSize=40});local after=parser.parse(filters.compile(p));assert.equal(source,p.template)
		assert.same(before.imports,after.imports);assert.equal(#before.rules,#after.rules)
		for i,rule in ipairs(before.rules) do assert.same(rule.conditions,after.rules[i].conditions);assert.equal(rule.action,after.rules[i].action);assert.equal(rule.continue,after.rules[i].continue) end
		local currency=after.rules[#after.rules-2];assert.same({"255","220","100","255"},currency.styles.SetTextColor);assert.same({"40"},currency.styles.SetFontSize)
		assert.same({"100","100","100"},after.rules[#after.rules-1].styles.SetTextColor)
	end)
	it("applies whole-filter overrides last and removes category settings reversibly",function()
		local p=profile();p.template=p.template:gsub('Import "external.filter"\n',"")
		p=categories.install(p,"Currency",{textColor={255,0,0,255}});local sample={BaseType="Chaos Orb",Class="Stackable Currency"}
		-- Continue retains the colour through later unmatched blocks and the final Show.
		assert.same({"255","0","0","255"},filters.simulate(p,sample).styles.SetTextColor)
		p.appearance={textColor={0,255,0,255}};assert.same({"0","255","0","255"},filters.simulate(p,sample).styles.SetTextColor)
		p.appearance=nil;p=categories.install(p,"Currency",nil);assert.same({"255","255","255"},filters.simulate(p,sample).styles.SetTextColor)
	end)
	it("styles generated targets and campaign policies in their own categories without moving them",function()
		local p=profile();p.template="Hide";p.rules={filters.rule("target","Target",{'BaseType == "Iron Hat"'},"craft:helmet")}
		p.campaign=require("Modules.LootFilterCampaign").defaults();p.campaign.weapons={"Bow"};p.campaign.upgradeWindow=0
		p=categories.install(p,"Build targets",{textColor={1,2,3,255}});p=categories.install(p,"Campaign",{textColor={4,5,6,255}})
		assert.same({"1","2","3","255"},filters.simulate(p,{BaseType="Iron Hat"}).styles.SetTextColor)
		assert.same({"4","5","6","255"},filters.simulate(p,{BaseType="Crude Bow",Rarity="Normal",AreaLevel=12}).styles.SetTextColor)
		p.categoryStyles[2].enabled=false;assert.is_not.same({"4","5","6","255"},filters.simulate(p,{BaseType="Crude Bow",Rarity="Normal",AreaLevel=12}).styles.SetTextColor)
	end)
	it("captures category settings in new palettes and preserves them with older palette formats",function()
		local collections=require("Modules.LootFilterCollections");local p=categories.install(profile(),"Currency",{minimumFontSize=40})
		p=collections.install(p,"palettes",{id="snapshot",title="Snapshot",appearance={},categoryStyles=copyTable(p.categoryStyles)})
		p.categoryStyles={};local restored=collections.palette(p,"snapshot");assert.equal("Currency",restored.categoryStyles[1].category)
		restored=collections.install(restored,"palettes",{id="older",title="Older palette",appearance={alertVolume=0}});assert.same(restored.categoryStyles,collections.palette(restored,"older").categoryStyles)
	end)
	it("rejects unknown or duplicate categories and invalid appearance values",function()
		assert.has_error(function() categories.validate({{category="All items",appearance={}}}) end)
		assert.has_error(function() categories.validate({{category="Currency",appearance={}},{category="Currency",appearance={}}}) end)
		assert.has_error(function() categories.validate({{category="Currency",appearance={alertVolume=-1}}}) end)
		assert.has_error(function() categories.validate({{category="Currency",appearance={},enabled="yes"}}) end)
	end)
end)
