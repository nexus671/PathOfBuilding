describe("Graphical RGBA picker",function()
	local picker=require("Classes.ColourPickerControl")
	local function run(callback)
		newBuild();main.popups={};local ui=require("Modules.HeadlessUI").install({width=1024,height=768})
		local ok,err=pcall(callback,ui);ui:restore();main.popups={};assert.is_true(ok,err)
	end
	it("keeps exact typed byte values and applies only when accepted",function()
		run(function(ui)
			local accepted;picker.Open({255,0,0,128},function(value) accepted=value end)
			ui:text("hex","61D8ED80");assert.is_nil(accepted);ui:click("keep");assert.same({97,216,237,128},accepted)
			picker.Open(accepted,function() error("Cancel applied a colour") end);ui:text("r","123");ui:click("cancel")
		end)
	end)
	it("prevents invalid RGBA and Ruthless text opacity from being accepted",function()
		run(function(ui)
			local c=picker.Open({255,255,255,0},function(value) assert.equal(80,value[4]) end,{minimumAlpha=80})
			assert.equal("80",c.a.buf);ui:text("a","0");assert.is_false(c.keep:IsEnabled());ui:text("a","80")
			ui:text("r","999");assert.is_false(c.keep:IsEnabled());ui:text("r","255");assert.is_true(c.keep:IsEnabled());ui:click("keep")
		end)
	end)
	it("supports left dragging and stops updating after a lost release",function()
		run(function(ui)
			local c=picker.Open({255,0,0,255},function() end);local x,y=c.wheel:GetPos()
			ui:dragAt(x+192,y+128,-64,64,"LEFTBUTTON");assert.equal("255",c.g.buf)
			ui.cursorX,ui.cursorY=x+192,y+128;ui:dispatch(ui:activeHost(),{{type="KeyDown",key="LEFTBUTTON"}});local before=c.hex.buf
			ui.keys.LEFTBUTTON=nil;ui.cursorX,ui.cursorY=x+64,y+128;ui:frame();assert.equal(before,c.hex.buf);assert.is_false(c.wheel.dragging);ui:click("cancel")
		end)
	end)
end)
