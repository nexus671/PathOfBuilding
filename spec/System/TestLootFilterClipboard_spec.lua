-- cspell:ignore RGBW
describe("Copied loot-filter items",function()
	local clipboard=require("Modules.LootFilterClipboard")
	local parser=require("Modules.LootFilterParser")
	it("retains explicitly marked unidentified item tiers without inventing missing tiers",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86\n--------\n"
		local item=clipboard.parse(raw.."Unidentified (Tier 4)")
		assert.is_false(item.Identified);assert.equal(4,item.UnidentifiedItemTier)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n Identified False\n UnidentifiedItemTier >= 4\nShow"),item).action)
		assert.equal("unknown",parser.simulate(parser.parse('Show\n HasExplicitMod "Life"\nHide'),item).status)
		local plain=clipboard.parse(raw.."Unidentified");assert.is_false(plain.Identified);assert.is_nil(plain.UnidentifiedItemTier)
		local unsupported=clipboard.parse(raw.."Unidentified (Tier 9)");assert.is_false(unsupported.Identified);assert.is_nil(unsupported.UnidentifiedItemTier)
		local text=clipboard.parse(raw.."Unidentified (Tier 4) modifier text");assert.is_true(text.Identified);assert.is_nil(text.UnidentifiedItemTier)
	end)
	it("reads visible equipment properties without inventing hidden modifier identities",function()
		local item=clipboard.parse("Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nQuality: +20% (augmented)\nSockets: R-G-B W\nItem Level: 86\n--------\nUnidentified\nCorrupted",72)
		assert.equal("Iron Hat",item.BaseType);assert.equal("Helmets",item.Class);assert.equal(20,item.Quality);assert.equal(4,item.Sockets);assert.equal("RGBW",item.SocketColours);assert.equal(3,item.LinkedSockets);assert.equal(72,item.AreaLevel)
		assert.is_false(item.Identified);assert.is_true(item.Corrupted);assert.is_nil(item.HasExplicitMod);assert.is_nil(item.FracturedItem)
		local numeric=parser.parse("Show\n Sockets >= 4").rules[1].conditions[1];local colors=parser.parse("Show\n Sockets RGB").rules[1].conditions[1]
		assert.is_true(parser.condition(numeric,item));assert.is_true(parser.condition(colors,item))
	end)
	it("accepts currency stacks and rejects unrelated clipboard text",function()
		local item=clipboard.parse("Item Class: Stackable Currency\nRarity: Currency\nChaos Orb\n--------\nStack Size: 7/20",83)
		assert.equal("Chaos Orb",item.BaseType);assert.equal(7,item.StackSize);assert.equal("Normal",item.Rarity)
		assert.is_false(pcall(clipboard.parse,"some other clipboard text"));assert.is_false(pcall(clipboard.parse,"Rarity: Magic\nImaginary Unknown Base\n--------"))
	end)
	it("requires whole-line state markers and rejects non-finite visible numbers",function()
		local raw="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nItem Level: 86\nCorrupted Blood cannot be inflicted on you"
		assert.is_false(clipboard.parse(raw).Corrupted)
		assert.is_false(pcall(clipboard.parse,raw:gsub("Item Level: 86","Item Level: "..string.rep("9",400))))
	end)
	it("recognizes twice-corrupted items as corrupted without guessing from modifier text",function()
		local raw="Item Class: Helmets\nRarity: Normal\nIron Hat\n--------\nItem Level: 86"
		local twice=clipboard.parse(raw.."\nTwice Corrupted")
		assert.is_true(twice.Corrupted);assert.is_true(twice.TwiceCorrupted)
		local once=clipboard.parse(raw.."\nCorrupted");assert.is_true(once.Corrupted);assert.is_false(once.TwiceCorrupted)
		local plain=clipboard.parse(raw.."\nTwice Corrupted modifiers");assert.is_false(plain.Corrupted);assert.is_false(plain.TwiceCorrupted)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n Corrupted True\n TwiceCorrupted True\nShow"),twice).action)
	end)
	it("reads influence markers on ordinary equipment without inferring unique or map influence",function()
		local raw="Item Class: Helmets\nRarity: Rare\nFoe Visage\nIron Hat\n--------\nItem Level: 86"
		local both=clipboard.parse(raw.."\nShaper Item\nElder Item")
		assert.same({"Shaper","Elder"},both.HasInfluence);assert.is_true(both.ShaperItem);assert.is_true(both.ElderItem)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n HasInfluence Elder\n ShaperItem True\nShow"),both).action)
		local none=clipboard.parse(raw.."\nShaper Item modifier text");assert.same({"None"},none.HasInfluence);assert.is_false(none.ShaperItem)
		assert.equal("Hide",parser.simulate(parser.parse("Hide\n HasInfluence None\n ElderItem False\nShow"),none).action)
		local unique=clipboard.parse("Item Class: Helmets\nRarity: Unique\nGoldrim\nLeather Cap\n--------\nItem Level: 86")
		assert.is_nil(unique.HasInfluence);assert.is_nil(unique.ShaperItem)
		local map=clipboard.parse("Item Class: Maps\nRarity: Normal\nStrand Map\n--------\nMap Tier: 1")
		assert.is_nil(map.HasInfluence);assert.is_nil(map.ElderItem)
	end)
	it("normalizes copied gem classes to the filter language",function()
		for label,class in pairs({["Active Skill Gems"]="Skill Gems",["Support Skill Gems"]="Support Gems"}) do
			local item=clipboard.parse("Item Class: "..label.."\nRarity: Gem\nAdded Fire Damage Support\n--------\nLevel: 12\nQuality: +20%",70)
			assert.equal(class,item.Class);assert.equal(12,item.GemLevel)
			assert.equal("matched",parser.simulate(parser.parse('Show\n Class == "'..class..'"\n Quality >= 1'),item).status)
		end
	end)
end)
