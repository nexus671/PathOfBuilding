describe("Pinned Covens tree preview",function()
	local atlas=require("Modules.AtlasPlanner")
	before_each(function() newBuild();main.popups={} end)
	after_each(function() main.popups={} end)
	it("defaults new builds to the published 3.30 tree",function()
		assert.equal("3_30",latestTreeVersion);assert.equal("3_30",build.spec.treeVersion)
		local tree=main:LoadTree("3_30_preview");assert.equal("3_30_preview",tree.treeVersion);assert.is_truthy(tree.classes[0]);assert.is_truthy(tree.secondaryAscendNameMap.Abyssal)
		assert.equal("3_30",build.spec.treeVersion)
	end)
	it("keeps an existing 3.29 build on its saved tree",function()
		build.treeTab:ConvertToVersion("3_29",true,false,true);runCallback("OnFrame")
		local bridge=require("Modules.DesktopBuildBridge");local prepared=bridge.prepare(build,{mode="edit",title="Existing 3.29 build",baseRevision=bridge.revision(build),operations={{type="set_character",level=80}}})
		assert.equal("3_29",prepared.candidate.spec.treeVersion);assert.equal("3_29",build.spec.treeVersion)
	end)
	it("preserves preview selection in native XML and exposes the calculation warning",function()
		build.treeTab:ConvertToVersion("3_30_preview",true,false,true);runCallback("OnFrame")
		assert.equal("3_30_preview",build.spec.treeVersion);assert.is_truthy(table.concat(build.controls.warnings.lines," "):find("preview",1,true))
		assert.is_truthy(build.treeTab.controls.specConvertText:GetProperty("label"):find("Preview tree",1,true))
		local bridge=require("Modules.DesktopBuildBridge");local prepared=bridge.prepare(build,{mode="edit",title="Preserve preview",baseRevision=bridge.revision(build),operations={{type="set_character",level=80}}})
		assert.equal("3_30_preview",prepared.candidate.spec.treeVersion)
		local found=false;for _,row in ipairs(prepared.audit.assumptions) do if row.key=="previewTree" then found=true end end;assert.is_true(found)
	end)
	it("uses the official 150 point Atlas and preserves the pinned legacy limits",function()
		local tree=atlas.tree("3.30.0-preview");assert.equal(150,tree.maxPoints);assert.is_true(tree.preview);assert.equal("d225501d7a3e52c991309116473908c284075e89",tree.commit)
		assert.equal("Massing Forces",tree.nodes[14287].name);assert.equal(3,#tree.nodes[14287].stats)
		local plan=atlas.connect({id="covens",title="Covens Breach",version="3.30.0-preview",budget=150,nodes={}},{14287})
		local report=atlas.report(plan);assert.is_true(report.preview);assert.equal("Covens of Umbra",report.compatibleModes[2]);assert.is_true(report.used>0)
		assert.equal(138,atlas.tree("3.29.1").maxPoints);assert.equal(138,atlas.tree("3.29.3").maxPoints)
		local invalid=copyTable(plan);invalid.version="3.29.1";assert.is_false(pcall(atlas.validate,invalid))
	end)
	it("round trips exact Atlas versions and requires explicit cross-version progression",function()
		local plan=atlas.connect({id="covens",title="Covens Breach",version="3.30.0-preview",budget=150,nodes={}},{14287})
		assert.same(plan,atlas.import(atlas.export(plan)))
		build.savers.AtlasPlans:Upsert({id="old",title="Old atlas",version="3.29.1",budget=138,nodes={}})
		plan.progression={stage="final",previousId="old"};assert.is_false(pcall(build.savers.AtlasPlans.Upsert,build.savers.AtlasPlans,plan))
	end)
end)
