describe("Native crafting item stat goals",function()
	local sim=require("Modules.CraftingSimulator")
	local stats=require("Modules.CraftingItemStats")
	local raw="Rarity: NORMAL\nRusted Sword\nItem Level: 86\nQuality: 20"
	it("matches native weapon values including fractional thresholds",function()
		local model=sim.model(raw);local values=stats.values(sim,model,model.initial)
		assert.are.equal(12.4,values.PhysicalDPS);assert.are.equal(1.55,values.AttackRate)
		assert.are.equal(0,values.ElementalDPS);assert.are.equal(0,values.ChaosDPS)
		assert.is_true(sim.matches(model.initial,{},nil,model,{nativeStats=values}))
		assert.is_false(sim.matches(model.initial,{},nil,model,{nativeStats={PhysicalDPS=12.401}}))
		assert.is_false(sim.matches(model.initial,{},nil,model,{nativeStats={AttackRate=1.551}}))
	end)
	it("updates goals and inspection after quality enchantment replacement",function()
		local model=sim.model(raw);local changed=sim.perform(raw,{method="harvest_enchant",enchantId="WeaponCriticalEnchant"},1)
		local values=stats.values(sim,model,changed.state)
		assert.is_true(values.PhysicalDPS<12.4);assert.are.equal(5.25,values.CritChance)
		assert.is_true(sim.matches(changed.state,{},nil,model,{nativeStats={CritChance=5.25}}))
		assert.is_false(sim.matches(changed.state,{},nil,model,{nativeStats={PhysicalDPS=12.4}}))
		assert.are.same(values,sim.catalog(raw,"",1,changed.state).nativeStats)
		assert.are.equal(12.4,stats.values(sim,model,model.initial).PhysicalDPS)
	end)
	it("uses native armour and Ward and rejects incompatible item stats",function()
		for _,base in ipairs({"Plate Vest","Runic Helm"}) do
			local model=sim.model("Rarity: NORMAL\n"..base.."\nItem Level: 86")
			local key=base=="Runic Helm" and "Ward" or "Armour";local values=stats.values(sim,model,model.initial)
			assert.is_true(values[key]>0);assert.is_true(sim.matches(model.initial,{},nil,model,{nativeStats={[key]=values[key]}}))
			assert.is_false(sim.matches(model.initial,{},nil,model,{nativeStats={[key]=values[key]+1}}))
			assert.is_false(sim.matches(model.initial,{},nil,model,{nativeStats={PhysicalDPS=0}}))
		end
	end)
	it("uses minimum stats as recipe stop conditions",function()
		local plain="Rarity: NORMAL\nRusted Sword\nItem Level: 86"
		local recipe={steps={{method="quality",maxAttempts=20,untilRequirements={nativeStats={PhysicalDPS=12.4}}}},targets={},requirements={nativeStats={PhysicalDPS=12.4}}}
		local result=sim.simulate(plain,recipe,{trials=3,maxActions=20,seed=123})
		assert.are.equal(3,result.successes);assert.is_true(result.meanActions>0)
		assert.is_true(result.sampleState.quality>0 and result.sampleState.quality<=20)
		assert.is_true(sim.matches(result.sampleState,{},nil,sim.model(plain),recipe.requirements))
	end)
	it("rejects unknown, empty and non-finite goals",function()
		for _,value in ipairs({{}, {Life=1}, {PhysicalDPS=-1}, {AttackRate="1.5"}, {CritChance=math.huge}, {Armour=0/0}}) do
			assert.is_false(pcall(sim.validateRecipe,{steps={{method="chaos"}},targets={},requirements={nativeStats=value}}))
		end
		assert.is_true(pcall(sim.validateRecipe,{steps={{method="chaos"}},targets={},requirements={nativeStats={AttackRate=1.55}}}))
	end)
	it("stages child edits and preserves goals through the parent editor",function()
		newBuild();local kept;local original={nativeStats={PhysicalDPS=12.4},minQuality=20}
		local c=require("Classes.CraftingTargetControl").Open({},original,nil,function(_,value) kept=value end)
		c.itemStats:Click();local child=main.popups[1].controls;child.PhysicalDPS:SetText("invalid");child.keep:Click()
		assert.are.equal("Item stat goals",main.popups[1].title);main.popups[1].controls.close:Click()
		assert.are.equal("invalid",child.PhysicalDPS.buf);child.PhysicalDPS:SetText("13.5");child.keep:Click()
		assert.are.same({PhysicalDPS=12.4},original.nativeStats);assert.is_nil(kept)
		c.keep:Click();assert.are.equal(13.5,kept.nativeStats.PhysicalDPS);assert.are.equal(20,kept.minQuality)
		main.popups={}
	end)
end)
